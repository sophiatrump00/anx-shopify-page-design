#!/usr/bin/env python3
"""Build the isolated Shopify preview from the local visual preview.

Run from any directory. Does not call Shopify or modify any existing template.
"""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
html = (Path(__file__).parent / 'index.html').read_text()
body = re.search(r'<body[^>]*>(.*)</body>', html, re.S).group(1).rstrip()
body = re.sub(
    r'../../assets/([\w.-]+)',
    lambda match: "{{ '" + match.group(1) + "' | asset_url }}",
    body,
)
body = body.replace('SuntNeew 12.8V 100Ah LiFePO4 RV Battery - Group 31', '{{ product.title | escape }}')
body = re.sub(r' data-total="[^"]*"', '', body)
for quantity, total in [(2, '$480.00'), (5, '$1,200.00'), (10, '$2,400.00')]:
    body = body.replace(total, '{{ g31_variant.price | times: ' + str(quantity) + ' | money }}')
body = body.replace('$240.00', '{{ g31_variant.price | money }}')
body = body.replace('$329.99', '{{ g31_variant.compare_at_price | money }}')
body = body.replace('<s data-compare-total>', '<s data-compare-total {% unless g31_variant.compare_at_price > g31_variant.price %}hidden{% endunless %}>')
body = body.replace('<span class="discount-tag">27% OFF</span>', '<span class="discount-tag" {% unless g31_variant.compare_at_price > g31_variant.price %}hidden{% endunless %}>{{ g31_discount }}% OFF</span>')
body = body.replace('5.0 (2 reviews)', '{{ g31_rating }} ({{ g31_review_count }} reviews)')
body = body.replace('aria-label="5 out of 5 stars"', 'aria-label="{{ g31_rating }} out of 5 stars" style="--rating-fill: {{ g31_rating | times: 20 }}%"')
body = body.replace('<strong>5.0</strong>', '<strong>{{ g31_rating }}</strong>')
body = body.replace('Based on 2 reviews', 'Based on {{ g31_review_count }} reviews')
body = body.replace(
    '<div data-live-reviews><p class="reviews-local-note">View the Shopify preview for the current customer reviews.</p></div>',
    '''<div id="judgeme_product_reviews" class="jdgm-widget jdgm-review-widget"
      data-product-title="{{ product.title | escape }}" data-id="{{ product.id }}" data-product-id="{{ product.id }}"
      data-widget="review" data-auto-install="false" data-shop-reviews="false"
      data-empty-state="empty_widget" data-entry-point="review_widget.js" data-entry-key="review-widget/main.js">
      {{ product.metafields.judgeme.widget }}
    </div>
    {%- if product.metafields.judgeme.review_widget_data != blank -%}
      <script>
        window.jdgm = window.jdgm || {};
        window.jdgm.data = window.jdgm.data || {};
        window.jdgm.data.reviewWidget = window.jdgm.data.reviewWidget || {};
        window.jdgm.data.reviewWidget[{{ product.id | json }}] = {{ product.metafields.judgeme.review_widget_data }};
      </script>
    {%- endif -%}''',
)

head = '''<!doctype html>
<html lang="{{ request.locale.iso_code }}">
  <head>
    <meta charset="utf-8">
    <meta name="viewport" content="width=device-width, initial-scale=1">
    <meta name="robots" content="noindex, nofollow">
    <meta name="theme-color" content="#ffffff">
    <title>G31 mobile preview | {{ shop.name | escape }}</title>
    <link rel="canonical" href="{{ canonical_url }}">
    {{ content_for_header }}
    {{ 'suntneew-g31-mobile-preview.css' | asset_url | stylesheet_tag }}
    <script src="{{ 'suntneew-g31-mobile-preview.js' | asset_url }}" defer></script>
  </head>
  {%- assign g31_variant = product.selected_or_first_available_variant -%}
  <body data-unit-price="{{ g31_variant.price }}" data-compare-price="{{ g31_variant.compare_at_price | default: 0 }}" data-currency="{{ cart.currency.iso_code | default: shop.currency }}" data-available="{{ g31_variant.available }}">
    {{ content_for_layout }}
  </body>
</html>
'''
template = '''{% comment %}Generated by tools/g31-litime-mobile-preview/build.py. Isolated preview only.{% endcomment %}
{%- layout 'g31-mobile-preview' -%}
{%- if product.handle == 'suntneew-12-8v-100ah-lifepo4-rv-battery-group-31' -%}
  {%- assign g31_variant = product.selected_or_first_available_variant -%}
  {%- assign g31_discount = 0 -%}
  {%- if g31_variant.compare_at_price > g31_variant.price -%}
    {%- assign g31_discount = g31_variant.compare_at_price | minus: g31_variant.price | times: 100.0 | divided_by: g31_variant.compare_at_price | round -%}
  {%- endif -%}
  {%- assign g31_rating = product.metafields.reviews.rating.value.rating | default: 0 | round: 1 -%}
  {%- assign g31_review_count = product.metafields.reviews.rating_count.value | default: 0 -%}
'''
template += body
template += '''
{%- else -%}
  <p>This preview is for the SuntNeew Group 31 battery.</p>
{%- endif -%}
'''
(ROOT / 'layout/g31-mobile-preview.liquid').write_text(head)
(ROOT / 'templates/product.g31-mobile-preview.liquid').write_text(template)
print('Built layout/g31-mobile-preview.liquid and templates/product.g31-mobile-preview.liquid')
